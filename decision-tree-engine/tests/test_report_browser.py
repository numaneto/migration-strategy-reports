import csv
import importlib.util
import tempfile
import unittest
from pathlib import Path

from test_engine import data, engine, vm


@unittest.skipUnless(importlib.util.find_spec("playwright"), "Optional Playwright browser tests require Playwright and Chromium")
class ReportBrowserTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from playwright.sync_api import sync_playwright

        cls.directory = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls.directory.cleanup)
        cls.playwright = sync_playwright().start()
        cls.addClassCleanup(cls.playwright.stop)
        executable = cls.playwright.chromium.executable_path
        if not Path(executable).is_file():
            raise unittest.SkipTest("Optional browser tests require Chromium: python -m playwright install chromium")
        cls.browser = cls.playwright.chromium.launch(executable_path=executable)
        cls.addClassCleanup(cls.browser.close)
        machines = [
            vm('READY-1, "quoted"'),
            vm("READY-DC", application="Domain Controller"),
            vm("CONDITION-1", os="Windows Server 2012 R2"),
            vm("PENDING-1", os="Unknown"),
            vm("BLOCKED-1", dynamic_os_disk=True),
        ]
        for index, machine in enumerate(machines, 1):
            machine["networks"][0]["ips"] = [f"10.10.10.{index}"]
        cls.result = engine.generate(data(*machines), "all")
        cls.path = engine.write_reports(cls.result, Path(cls.directory.name))

    def setUp(self):
        self.page = self.browser.new_page(accept_downloads=True, viewport={"width": 1440, "height": 1100})
        self.addCleanup(self.page.close)
        self.errors = []
        self.requests = []
        self.page.on("pageerror", lambda error: self.errors.append(str(error)))
        self.page.on("request", lambda request: self.requests.append(request.url)
                     if request.url.startswith(("http:", "https:")) else None)
        self.page.goto(self.path.as_uri())
        self.assertEqual(self.errors, [])

    def tearDown(self):
        self.assertEqual(self.errors, [])
        self.assertEqual(self.requests, [])

    def test_multilingual_status_filters_and_footer(self):
        footers = [
            "Report generated by AI Skill - Should be reviewed by your CFTL or Architect.",
            "Relatório gerado por Skill de IA - Deve ser revisado pelo seu CFTL ou Arquiteto.",
            "Informe generado por Skill de IA - Debe ser revisado por su CFTL o Arquitecto.",
        ]
        for language in range(3):
            self.page.locator(".language").select_option(str(language))
            self.assertEqual(self.page.locator('footer [data-label="footer"]').inner_text(), footers[language])
            for status, count in (("all", 5), ("ready", 2), ("ready-conditions", 1), ("not-ready", 1), ("unknown", 1)):
                self.page.locator(".status-filter").select_option(status)
                self.assertEqual(self.page.locator(".vm-readiness tbody tr").count(), count, (language, status))
                self.assertIn(f"{count}", self.page.locator(".vm-count").inner_text())
            self.page.locator(".clear-filters").click()
            self.page.locator('.cards [data-status="ready"]').click()
            self.assertEqual(self.page.locator(".status-filter").input_value(), "ready")
            self.assertEqual(self.page.locator(".vm-readiness tbody tr").count(), 2)
        self.page.locator(".clear-filters").click()
        self.page.locator(".search").fill("Windows Server 2012")
        self.assertEqual(self.page.locator(".vm-readiness tbody tr").count(), 1)
        self.page.locator(".status-filter").select_option("ready")
        self.assertEqual(self.page.locator(".vm-readiness tbody tr").count(), 0)
        self.page.locator(".clear-filters").click()
        self.assertEqual(self.page.locator(".vm-readiness tbody tr").count(), 5)

    def test_nested_status_action_vm_tree_and_separate_checks(self):
        for language in range(3):
            self.page.locator(".language").select_option(str(language))
            self.page.locator(".view").select_option("tree")
            for grouping in ("issue", "action"):
                self.page.locator(".group").select_option(grouping)
                self.page.locator(".status-filter").select_option("all")
                self.assertEqual(self.page.locator(".tree-root > .status-branch").count(), 4)
                ids = self.page.locator(".vm-leaf").evaluate_all("(nodes)=>nodes.map(n=>n.dataset.vmId)")
                self.assertEqual(len(set(ids)), 5)
                condition = self.page.locator('.status-branch[data-status="ready-conditions"]')
                self.assertEqual(condition.locator(".vm-leaf").count(), 1)
                self.assertIn("2012" if grouping == "issue" else "ESU",
                              condition.locator(".action-branch > summary").first.inner_text())
                self.page.locator(".expand-all").click()
                self.assertEqual(self.page.locator(".tree details:not([open])").count(), 0)
                self.assertGreater(self.page.locator(".vm-leaf .rule-detail a").count(), 0)
                self.assertIn("FACTORY-EXCLUDED", self.page.locator('.vm-leaf[data-vm-id="READY-DC"]').inner_text())
                self.page.locator(".zoom").fill("120")
                self.assertEqual(self.page.locator(".tree details:not([open])").count(), 0)
                self.page.locator(".collapse-all").click()
                self.assertEqual(self.page.locator(".tree details[open]").count(), 0)
                self.page.locator(".status-filter").select_option("not-ready")
                self.assertEqual(self.page.locator(".status-branch").count(), 1)
                self.assertEqual(self.page.locator(".vm-leaf").count(), 1)
        self.page.locator(".scenario").select_option("aws-azure")
        self.page.locator(".status-filter").select_option("ready")
        self.assertEqual(self.page.locator(".vm-leaf").count(), 0)
        self.assertIn("0", self.page.locator(".vm-count").inner_text())

    def test_filtered_unique_vm_and_complete_action_exports(self):
        for language in range(3):
            self.page.locator(".language").select_option(str(language))
            self.page.locator(".status-filter").select_option("ready")
            for button, expected_columns, name_column in ((".export-vms", 7, 0), (".export", 10, 1)):
                with self.page.expect_download() as downloaded:
                    self.page.locator(button).click()
                destination = Path(self.directory.name) / f"export-{language}-{name_column}.csv"
                downloaded.value.save_as(destination)
                with destination.open(encoding="utf-8-sig", newline="") as stream:
                    records = list(csv.reader(stream))
                self.assertTrue(all(len(row) == expected_columns for row in records))
                self.assertEqual({row[name_column] for row in records[1:]}, {'READY-1, "quoted"', "READY-DC"})
                if button == ".export-vms":
                    self.assertEqual(len(records), 3)
                else:
                    self.assertTrue(any("FACTORY-EXCLUDED" in row[8] for row in records[1:]))
        self.page.locator(".scenario").select_option("aws-azure")
        with self.page.expect_download() as downloaded:
            self.page.locator(".export-vms").click()
        destination = Path(self.directory.name) / "empty.csv"
        downloaded.value.save_as(destination)
        with destination.open(encoding="utf-8-sig", newline="") as stream:
            self.assertEqual(len(list(csv.reader(stream))), 1)
